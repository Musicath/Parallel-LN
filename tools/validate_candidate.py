"""Run the non-training release checks in the active Python environment.

This is a smoke check, not a fresh-install check or a reproduction of the
manuscript's training runs. It does not download datasets or use a GPU.
"""

from __future__ import annotations

import importlib.metadata
import os
from pathlib import Path
import subprocess
import sys
import time


ROOT = Path(__file__).resolve().parents[1]
PYTHON = sys.executable
EXPECTED_PLOTS = (
    "fig_cnn_d4_grouping_3seed.pdf",
    "fig_cnn_grouping_direction.pdf",
    "fig_vit_clean50k_two_modes_3seed.pdf",
    "fig_vit_random6k_two_modes_3seed.pdf",
    "fig_vit_random20k_two_modes_3seed.pdf",
    "fig_vit_grouping_direction_20k.pdf",
    "fig_normalization_domains.pdf",
    "fig_normalization_domains.png",
)


def package_version(name: str) -> str:
    try:
        return importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError:
        return "not installed"


def run(*args: str, quiet: bool = False) -> None:
    command = (PYTHON, *args)
    print("RUN", " ".join(args), flush=True)
    completed = subprocess.run(
        command,
        cwd=ROOT,
        env={**os.environ, "MPLBACKEND": "Agg"},
        stdout=subprocess.DEVNULL if quiet else None,
        check=False,
    )
    if completed.returncode:
        raise SystemExit(f"FAILED ({completed.returncode}): {' '.join(args)}")


def main() -> None:
    print(f"Python: {sys.version.split()[0]}")
    for name in ("torch", "torchvision", "numpy", "matplotlib", "deepxde"):
        print(f"{name}: {package_version(name)}")
    print("These checks do not validate a fresh installation or full training.", flush=True)

    for optimized in (False, True):
        option = ("-O",) if optimized else ()
        run(*option, "-m", "unittest", "discover", "-s", "tests", "-v")
        for script in (
            "figures/verify_data.py",
            "figures/verify_fourier_data.py",
            "experiments/pinn/verify_data.py",
        ):
            run(*option, script)

    help_commands = (
        ("experiments/dense_fourier/run_dense_fourier_mlp.py",),
        ("experiments/cnn/run_cifar10_conv_gn_random_labels.py",),
        ("experiments/cnn/run_cifar10_conv_gn_clean_labels.py",),
        ("-m", "experiments.cnn.run_cifar10_conv_gn_random_labels"),
        ("-m", "experiments.cnn.run_cifar10_conv_gn_clean_labels"),
        ("-m", "experiments.vgg.train_cifar10"),
        ("-m", "experiments.vgg.make_grid_plan"),
        ("-m", "experiments.vgg.summarize_grid"),
        ("-m", "experiments.vgg.plot_grid"),
        ("-m", "experiments.vgg_bias_init.train"),
        ("-m", "experiments.vgg_bias_init.make_plan"),
        ("-m", "experiments.vit.prepare_fixed_labels"),
        ("-m", "experiments.vit.train_vit_token_grouping"),
        ("experiments/pinn/run_helmholtz.py",),
    )
    for command in help_commands:
        run(*command, "--help", quiet=True)
    run("experiments/pinn/run_helmholtz.py", "--protocol", "table2",
        "--optimizer", "sgd", "--dry-run", quiet=True)
    run("experiments/pinn/run_helmholtz.py", "--protocol", "ntk",
        "--lbfgs-steps", "1200", "--dry-run", quiet=True)

    plot_started = time.time()
    run("figures/plot_from_csv.py")
    run("figures/plot_normalization_domain_schematic.py")
    generated = ROOT / "figures" / "generated"
    for name in EXPECTED_PLOTS:
        path = generated / name
        if not path.is_file() or path.stat().st_size < 1024:
            raise SystemExit(f"Missing or empty generated plot: {path}")
        if path.stat().st_mtime < plot_started - 2:
            raise SystemExit(f"Plot was not regenerated by this check: {path}")
    print("PASS: tests, data checks, entrypoints, and eight plots.")


if __name__ == "__main__":
    main()
